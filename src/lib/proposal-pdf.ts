import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { supabase } from "@/integrations/supabase/client";
import { propertyWord } from "@/lib/constants";

export type ProposalData = {
  clientId: string;
  hotelName: string;
  propertyType?: string | null | undefined;
  clientCode?: string | null | undefined;
  planName: string;
  basedOn?: string | null | undefined;
  retainerInr: number | null;
  commission: { direct: number | null; ota: number | null; weddings: number | null };
  teamIncentivePct?: number | null | undefined;
  setupFeeInr?: number | null | undefined;
  services: Array<{ name: string; scope?: string | null; frequency?: string | null }>;
  addOns: Array<{ name: string; price: string }>;
  thirdPartyCosts: string;
  thirdPartyItems: string[];
  payment: { billingBasis?: string | null | undefined; invoiceDay?: number | null | undefined; dueDay?: number | null | undefined; lateInterestPct?: number | null | undefined; cycle?: string | null | undefined };
  noticeDays?: number | null | undefined;
  minTermMonths?: number | null | undefined;
  annualRevisionPct?: number | null | undefined;
  validUntil: string;
  contact: { name: string; email?: string | null | undefined; mobile?: string | null | undefined };
};

const NAVY: [number, number, number] = [15, 27, 56];
const GOLD: [number, number, number] = [193, 154, 76];
// Built-in PDF fonts have no ₹ glyph.
const rs = (n: number | null | undefined) => (n == null ? "—" : `Rs. ${new Intl.NumberFormat("en-IN").format(Number(n))}`);
const pct = (v: number | null | undefined) => (v == null ? "Not specified" : `${v}%`);
const date = (d: string) => new Date(`${d}T00:00:00Z`).toLocaleDateString("en-IN", { day: "2-digit", month: "long", year: "numeric", timeZone: "UTC" });

export function buildProposalPdf(p: ProposalData): jsPDF {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, W, 96, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("Alcor Getaways", 40, 44);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(`${propertyWord(p.propertyType) === "hotel" ? "Hotel" : "Property"} Sales & Marketing Partnership — Proposal`, 40, 66);
  doc.setFillColor(...GOLD);
  doc.rect(0, 96, W, 4, "F");

  doc.setTextColor(...NAVY);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(p.clientCode ? `${p.hotelName}  (${p.clientCode})` : p.hotelName, 40, 132);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Plan: ${p.planName}${p.basedOn ? ` (based on ${p.basedOn})` : ""}`, 40, 150);
  doc.text(`Prepared ${date(new Date().toISOString().slice(0, 10))} · Valid until ${date(p.validUntil)}`, 40, 164);

  const section = (title: string, y: number) => {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(...NAVY);
    doc.text(title, 40, y);
    doc.setDrawColor(...GOLD);
    doc.line(40, y + 4, W - 40, y + 4);
    return y + 12;
  };
  const table = (startY: number, head: string[] | null, body: string[][]) => {
    autoTable(doc, {
      startY,
      ...(head ? { head: [head] } : {}),
      body,
      theme: "grid",
      styles: { fontSize: 9, cellPadding: 4, textColor: [30, 30, 30] },
      headStyles: { fillColor: NAVY, textColor: [255, 255, 255] },
      columnStyles: head ? {} : { 0: { cellWidth: 170, fontStyle: "bold" } },
      margin: { left: 40, right: 40 },
    });
    return (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 22;
  };

  let y = section("Fees", 196);
  const fees: string[][] = [["Monthly retainer", `${rs(p.retainerInr)} per month + GST`]];
  if (p.setupFeeInr) fees.push(["One-time setup fee", `${rs(p.setupFeeInr)} + GST`]);
  fees.push(["Commission — direct bookings", pct(p.commission.direct)]);
  fees.push(["Commission — OTA bookings", pct(p.commission.ota)]);
  fees.push(["Commission — weddings / events", pct(p.commission.weddings)]);
  if (p.teamIncentivePct) fees.push(["Team incentive", `${p.teamIncentivePct}% of revenue generated by Alcor teams`]);
  y = table(y, null, fees);

  y = section("Services included", y);
  y = table(y, ["Service", "Scope", "Frequency"], p.services.map((s) => [s.name, s.scope ?? "", s.frequency ?? ""]));

  if (p.addOns.length) {
    y = section("Optional add-ons", y);
    y = table(y, ["Add-on", "Price"], p.addOns.map((a) => [a.name, a.price]));
  }

  y = section("Third-party costs", y);
  y = table(y, null, [["Who pays", p.thirdPartyCosts], ["Covers", p.thirdPartyItems.join(", ")]]);

  y = section("Payment & contract terms", y);
  const t = p.payment;
  y = table(y, null, [
    ["Billing", `${t.billingBasis ?? "advance"}${t.cycle ? ` · ${t.cycle}` : ""}`],
    ["Invoice / due", t.invoiceDay ? `Invoice on the ${t.invoiceDay}, due by the ${t.dueDay ?? "—"} of the month` : "—"],
    ["Late payment interest", t.lateInterestPct ? `${t.lateInterestPct}% p.a.` : "None"],
    ["Notice period", p.noticeDays != null ? `${p.noticeDays} days` : "—"],
    ["Minimum term", p.minTermMonths ? `${p.minTermMonths} months` : "None"],
    ["Annual fee revision", p.annualRevisionPct ? `${p.annualRevisionPct}% on each contract anniversary` : "Not applicable"],
  ]);

  if (y > 720) { doc.addPage(); y = 60; }
  y = section("Your Alcor contact", y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(30, 30, 30);
  doc.text([p.contact.name, p.contact.email ?? "", p.contact.mobile ?? ""].filter(Boolean), 40, y + 6);
  doc.setFontSize(8);
  doc.setTextColor(120, 120, 120);
  doc.text("This proposal is not a contract. The signed partnership agreement governs the final terms.", 40, 810);
  return doc;
}

/** Builds the PDF, downloads it, and saves a copy to the client's documents. */
export async function generateAndSaveProposal(p: ProposalData, userId: string | undefined) {
  const doc = buildProposalPdf(p);
  const stamp = new Date().toISOString().slice(0, 10);
  const fileName = `Alcor proposal - ${p.hotelName} - ${stamp}.pdf`;
  const blob = doc.output("blob");
  const path = `${p.clientId}/proposals/${stamp}-${crypto.randomUUID().slice(0, 8)}.pdf`;
  const up = await supabase.storage.from("client-files").upload(path, blob, { contentType: "application/pdf" });
  if (up.error) throw up.error;
  const { error } = await supabase.from("documents").insert({
    client_id: p.clientId, category: "proposal", doc_type: `Proposal — ${p.planName}`, file_path: path,
    status: "uploaded", notes: `Generated ${stamp}, valid until ${p.validUntil}`, uploaded_by: userId ?? null,
    generated_proposal: true,
  });
  if (error) throw error;
  doc.save(fileName);
}

/** The proposal's contact is always the hotel's Account Manager (falls back to Alcor Getaways). */
export async function accountManagerContact(clientId: string): Promise<ProposalData["contact"]> {
  const { data: c } = await supabase.from("clients").select("account_manager_id").eq("id", clientId).maybeSingle();
  if (!c?.account_manager_id) return { name: "Alcor Getaways" };
  const { data: p } = await supabase.from("profiles").select("full_name, email, mobile").eq("id", c.account_manager_id).maybeSingle();
  return p ? { name: `${p.full_name} — Account Manager`, email: p.email, mobile: p.mobile } : { name: "Alcor Getaways" };
}
